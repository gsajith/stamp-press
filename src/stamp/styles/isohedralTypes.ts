// How a tiling edge may bend, given the symmetries the tiling forces on it: J any way, U symmetric across its
// perpendicular bisector, S symmetric under a half turn about its middle, I straight.
export type EdgeShape = "J" | "U" | "S" | "I";

// One isohedral type, IH1 to IH93. Its prototile has `vertices` tiling vertices, placed by `params` free
// parameters through `vertexCoeffs`. A coefficient table holds, per output number, one coefficient per parameter
// plus one for the constant 1 appended to the parameters. `aspects` copies of the prototile, placed by
// `aspectCoeffs` as 2x3 matrices, make one translational unit, repeated along the two translation vectors.
export type TilingType = {
  type: number;
  params: number;
  aspects: number;
  vertices: number;
  // The shape of each distinct edge, by edge shape id.
  edgeShapes: readonly EdgeShape[];
  // Per tiling edge, the edge shape id it draws, and whether it's flipped and whether it's turned, as 0 or 1.
  edgeShapeIds: readonly number[];
  edgeOrientations: readonly number[];
  defaultParams: readonly number[];
  vertexCoeffs: readonly number[];
  translationCoeffs: readonly number[];
  aspectCoeffs: readonly number[];
  // The tile colouring: an aspect's colour in the unit at the origin (12 entries), the colour a tile takes one
  // step along t1 (3) and along t2 (3), given its colour, and the period of those steps.
  colouring: readonly number[];
};

